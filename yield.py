df2 = df[df["Crop"] != "Coconut"].copy()

def build():
    pre = ColumnTransformer(
        [("cat", OneHotEncoder(handle_unknown="ignore"), cat)],
        remainder="passthrough",
    )
    xgb = XGBRegressor(n_estimators=400, max_depth=6, learning_rate=0.08,
                       subsample=0.8, colsample_bytree=0.8, random_state=42)
    return Pipeline([("pre", pre),
                     ("xgb", TransformedTargetRegressor(
                         regressor=xgb, func=np.log1p, inverse_func=np.expm1))])

X2, y2 = df2[cat + num], df2["Yield"]

# 1) Random split
Xa, Xb, ya, yb = train_test_split(X2, y2, test_size=0.2, random_state=42)
m1 = build().fit(Xa, ya)
print("Random split -> R2:", round(r2_score(yb, m1.predict(Xb)), 3),
      "MAE:", round(mean_absolute_error(yb, m1.predict(Xb)), 3))

# 2) Time-based split (last ~4 saal test)
cut = df2["Crop_Year"].max() - 4
tr, te = df2[df2["Crop_Year"] <= cut], df2[df2["Crop_Year"] > cut]
m2 = build().fit(tr[cat + num], tr["Yield"])
p2 = m2.predict(te[cat + num])
print(f"Time split (test > {cut}) -> R2:", round(r2_score(te["Yield"], p2), 3),
      "MAE:", round(mean_absolute_error(te["Yield"], p2), 3))

# 3) Final model: poore data pe train
final = build().fit(X2, y2)

import pickle, sys, sklearn, xgboost
with open("yield_model.pkl", "wb") as f:
    pickle.dump(final, f)

